// Run through tsx with the S5 sdkMaker.ts module and pinned SDK module paths as arguments.
// No wallet, keys, HTTP or RPC: only the adapter's unsigned prepare methods are invoked.
import {writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const {createSDKMakerIO}=await import(pathToFileURL(process.argv[2]));
const {Zkp2pClient,getContracts}=await import(pathToFileURL(process.argv[3]));
const contracts=getContracts(8453,'production');
const sdk=new Zkp2pClient({chainId:8453,walletClient:{},rpcUrl:'https://unused.invalid'});
const terms={minimum:'1000000',maximum:'5000000',conversionRate:'1000000000000000000',validUntil:'2026-11-16T12:01:00Z'};
const io=createSDKMakerIO({sdk,discovery:{now:()=>Date.parse('2026-11-16T12:00:00Z')},reads:{},executionTerms:async()=>terms});
const intent={direction:'offramp',fiat:{currency:'USD'}};
const cases=[];
const tx=(p)=>({chain_id:p.chainId,to:p.to.toLowerCase(),data:p.data,value:p.value.toString()});
for(const amount of ['2000000','5000000']){
 cases.push({action:'approve_usdc',amount,transaction:tx(await io.prepareApproval(amount))});
 cases.push({action:'create_deposit',amount,rail:'revolut',payee_hash:'0x'+'3'.repeat(64),terms,transaction:tx(await io.prepareDeposit({intent,rail:'revolut',amount,payeeHash:'0x'+'3'.repeat(64)}))});
}
cases.push({action:'remove_funds',deposit_id:'7',amount:'1000000',transaction:tx(await io.prepareWithdrawal('7','1000000',false))});
cases.push({action:'withdraw_deposit',deposit_id:'7',amount:'2000000',transaction:tx(await io.prepareWithdrawal('7','2000000',true))});
const {serializeTransaction,keccak256}=await import(new URL('../../../viem/_esm/index.js',pathToFileURL(process.argv[3])));
const unsigned=serializeTransaction({type:'eip1559',chainId:8453,nonce:0,maxPriorityFeePerGas:1n,maxFeePerGas:3n,gas:100000n,to:contracts.addresses.usdc,value:0n,data:cases[0].transaction.data});
const output={unsigned_transaction:{serialized:unsigned,digest:keccak256(unsigned)},description:'Synthetic unsigned calldata only; generated by S5 createSDKMakerIO with the real pinned SDK, no network or signer.',sdk:'@zkp2p/sdk@0.15.0-rc.11',source:'xochi-sdk feature/ramp-peer-maker packages/widget/src/ramp/peer/sdkMaker.ts',cases};
writeFileSync(process.argv[4],JSON.stringify(output,null,2)+'\n');
